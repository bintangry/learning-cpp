#include <iostream>
#include <cmath>
using namespace std;

int main() {
    // disini kita cuma sedikit karena yang banyak ada di sesi math yang lebih kompleks
    // disini kita belajar cari nilai tertinggi dan terendah antara 2 angka
    cout << max(10,5) << "\n";

    cout << min(47, 28) << "\n";

    // untuk memakai square root, round a number, log itu wajib memakai library <cmath>
    cout << sqrt(9) << "\n";
    cout << round(41.7) << "\n";
    cout << log(4) << "\n";

    return 0;
}